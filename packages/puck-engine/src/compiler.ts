import { scanComponentTree } from "./scanner.js";
export type { ComponentPropMetadata, PropEntry } from "./scanner.js";

export interface PuckEngineOptions {
  componentsDir: string;
  outputPath: string;
  /** Optional Vite alias prefix (e.g. "@trackdraft/components/"). If omitted, defaults to "./components/" for same-project imports. */
  importPrefix?: string;
}

export function runPuckASTCompiler(options: PuckEngineOptions): number {
  const components = scanComponentTree(options);
  compilePuckConfig({
    components,
    outputPath: options.outputPath,
    importPrefix: options.importPrefix,
  });
  return components.length;
}
