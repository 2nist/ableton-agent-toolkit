import fs from "node:fs";
import path from "node:path";
import type { ComponentPropMetadata, PropEntry } from "./scanner.js";

export interface CompilePuckOptions {
  components: ComponentPropMetadata[];
  outputPath: string;
  /** Optional Vite alias prefix (e.g. "@trackdraft/components/"). If provided, prepended to each component's relativePath. Otherwise resolved relative to the output file. */
  importPrefix?: string;
}

const TELEMETRY_PROP_NAMES = new Set(["liveBpm", "activeScale", "rootNote", "trackChords"]);

function puckFieldDef(prop: PropEntry): string {
  const { tsType } = prop;
  if (tsType === "boolean" || tsType === "radio") {
    return `{ type: "radio" as const, options: [{ label: "Yes", value: true }, { label: "No", value: false }] } as any`;
  }
  if (tsType === "number") return `{ type: "number" as const } as any`;
  if (tsType === "array") return `{ type: "array" as any, arrayFields: { type: "text" as const } } as any`;
  return `{ type: "text" as const } as any`;
}

function puckDefault(prop: PropEntry): string {
  const { name, tsType } = prop;
  const lc = name.toLowerCase();
  if (tsType === "boolean") return "false";
  if (tsType === "number") {
    if (lc.includes("bpm")) return "120";
    if (lc.includes("bar") || lc.includes("beat")) return "4";
    return "0";
  }
  if (tsType === "array") return "[]";
  // string default
  if (lc.includes("name") || lc === "title") return `"Demo"`;
  if (lc.includes("label")) return `"Label"`;
  if (lc === "key" || lc.includes("key")) return `"C"`;
  if (lc.includes("scale") || lc === "mode") return `"major"`;
  if (lc.includes("role")) return `"verse"`;
  return `""`;
}

export function compilePuckConfig(options: CompilePuckOptions): void {
  const { components, outputPath, importPrefix } = options;
  const outputDir = path.dirname(outputPath);

  let outputCode = `// ⚡ AUTOMATICALLY GENERATED BY @DEVKIT/PUCK-ENGINE
import { lazy, Suspense } from "react";
import type { ComponentType } from "react";
import type { Config } from "@measured/puck";

const telemetryUrl = (): string => {
  if (typeof window !== "undefined") {
    return (window as any).__ENV_TELEMETRY_URL || "http://localhost:5200/api/ableton/state";
  }
  return (typeof process !== "undefined" && (process as any).env?.TELEMETRY_URL)
    || "http://localhost:5200/api/ableton/state";
};

const componentLookup: Record<string, () => Promise<{ default: ComponentType<any> }>> = {
`;

  for (const comp of components) {
    let importPath: string;
    if (importPrefix) {
      importPath = importPrefix + comp.relativePath;
    } else {
      importPath = comp.relativePath;
      if (!importPath.startsWith(".")) importPath = "./" + importPath;
    }
    outputCode += `  ${JSON.stringify(comp.name)}: () => import(${JSON.stringify(importPath)}),\n`;
  }

  outputCode += `};

function LazyRenderer(loader: () => Promise<{ default: ComponentType<any> }>) {
  const Comp = lazy(loader);
  return function PuckRender(props: Record<string, unknown>) {
    return (
      <Suspense fallback={<div className="p-4 text-xs text-inkMuted animate-pulse">Loading…</div>}>
        <Comp {...(props as any)} />
      </Suspense>
    );
  };
}

export const generatedPuckConfig: Config<any> = {
  components: {
`;

  for (const comp of components) {
    const hasTelemetryProps = comp.props.some((p) => TELEMETRY_PROP_NAMES.has(p.name));

    outputCode += `    ${comp.name}: {\n`;
    outputCode += `      fields: {\n`;
    for (const prop of comp.props) {
      outputCode += `        ${prop.name}: ${puckFieldDef(prop)},\n`;
    }
    outputCode += `      },\n`;

    outputCode += `      defaultProps: {\n`;
    for (const prop of comp.props) {
      outputCode += `        ${prop.name}: ${puckDefault(prop)},\n`;
    }
    outputCode += `      },\n`;

    if (hasTelemetryProps) {
      const propListItems = comp.props
        .filter((p) => TELEMETRY_PROP_NAMES.has(p.name))
        .map((p) => `          ${p.name}: liveState.${p.name} ?? props.${p.name},`)
        .join("\n");
      const changedChecks = comp.props
        .filter((p) => TELEMETRY_PROP_NAMES.has(p.name))
        .map((p) => `changed.${p.name}`)
        .join(" || ");
      outputCode += `      resolveData: async ({ props, changed }, { lastData }) => {
        if (${changedChecks} || !lastData) {
          try {
            const res = await fetch(telemetryUrl());
            if (!res.ok) throw new Error(\`HTTP \${res.status}\`);
            const liveState: Record<string, unknown> = await res.json();
            return {
              props: {
                ...props,
${propListItems}
              },
            };
          } catch (err) {
            console.warn("[resolveData] telemetry fetch failed", err);
            return { props };
          }
        }
        return { props };
      },\n`;
    }

    outputCode += `      render: LazyRenderer(componentLookup[${JSON.stringify(comp.name)}]) as any,\n`;
    outputCode += `    },\n`;
  }

  outputCode += `  },\n};\n`;

  if (!fs.existsSync(outputDir)) {
    fs.mkdirSync(outputDir, { recursive: true });
  }

  fs.writeFileSync(outputPath, outputCode, "utf-8");
  console.log(`[PUCK-ENGINE] Generated puck config: ${outputPath} (${components.length} components)`);
}

