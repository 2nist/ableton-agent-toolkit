import { useMemo } from "react";
import {
  synthesizeTransition,
  scaleToVelocityPreset,
  tileGrooveVaried,
  applyVoiceOverrides,
  voiceOf,
  type PackedNote,
  type KitVoice,
} from "@drum/library";
import { resolveSectionVariant, velocityNumber } from "../../lib/playback/drumPreview";
import {
  beatsPerBar,
  sectionDurationBeats,
  type BlueprintSection,
  type BlueprintSong,
  type DrumTransitionModel,
} from "../../types/blueprint";
import { voiceColor, VOICE_LABEL, VOICE_ORDER } from "./voiceStyle";
import { useTransitionColors, TRANSITION_LABEL } from "./transitionStyle";
import { usePalette, withAlpha } from "../../theme/palette";

const round4 = (n: number): number => Math.round(n * 10000) / 10000;

interface PreviewRow {
  voice: KitVoice;
  hits: Set<number>;
}

/**
 * The actual material the export will play across a section's transition
 * bars — generated by the exact same `synthesizeTransition` the export
 * path uses (via `applySectionTransition` in `@drum/library`), so "Build
 * up" vs "Cut" vs "Drop out" read as visibly different shapes instead of
 * one shared placeholder. The groove that would otherwise play in the
 * span (with per-voice overrides applied, tiled to the section) is handed
 * in as `baseNotes`, exactly as the export does, so breakDown/dropOut thin
 * the *real* groove. Rendered as one compact step strip per voice on the
 * transition's own subdivision grid.
 */
export default function TransitionPreview({
  section,
  song,
  model,
  transitionBars,
}: {
  section: BlueprintSection;
  song?: BlueprintSong;
  model: DrumTransitionModel;
  transitionBars: number;
}) {
  const P = usePalette();
  const TRANSITION_COLOR = useTransitionColors();
  const { rows, steps, tooShort } = useMemo(() => {
    const variant = resolveSectionVariant(section, song);
    const barBeats = variant?.beatsPerBar ?? beatsPerBar(section);
    const gridBeats = section.drumMeterOutline?.cellBeats ?? 0.25;
    const durationBeats = sectionDurationBeats(section);

    const maxBars = Math.floor(durationBeats / barBeats);
    if (maxBars < 1) return { rows: [] as PreviewRow[], steps: 0, tooShort: true };
    const spanBars = Math.max(1, Math.min(Math.round(transitionBars), maxBars));
    // Same guard as the export: never eat the section's only bar.
    const tooShort = spanBars >= maxBars && maxBars < 2;
    const spanBeats = spanBars * barBeats;
    const fillStart = durationBeats - spanBeats;

    // The groove that would otherwise play in the span, relative to the
    // span's own start — the same `baseNotes` `applySectionTransition`
    // hands to the synthesizer, so breakDown/dropOut thin the real groove.
    let baseNotes: PackedNote[] = [];
    if (variant) {
      const eff = applyVoiceOverrides(variant, section.drumVoicePatterns ?? {}, { loopBeats: variant.lengthBeats });
      const scaled = scaleToVelocityPreset(eff.notes, velocityNumber(section.velocity));
      const tiled = tileGrooveVaried(
        scaled.map(([beat, pitch, velocity]) => ({ beat, pitch, velocity })),
        variant.lengthBeats,
        durationBeats,
        { seed: section.id },
      );
      baseNotes = tiled
        .filter((n) => n.beat >= fillStart)
        .map((n): PackedNote => [round4(n.beat - fillStart), n.pitch, n.velocity]);
    }

    const generated = synthesizeTransition(model, {
      spanBeats,
      gridBeats,
      velocityTarget: velocityNumber(section.velocity),
      baseNotes,
    });

    const totalSteps = Math.max(1, Math.round(spanBeats / gridBeats));
    const byVoice = new Map<KitVoice, number[]>();
    for (const [beat, pitch] of generated) {
      const v = voiceOf(pitch);
      if (!v) continue;
      const step = Math.min(totalSteps - 1, Math.round(beat / gridBeats));
      const list = byVoice.get(v) ?? [];
      if (!list.includes(step)) list.push(step);
      byVoice.set(v, list);
    }
    const rows: PreviewRow[] = Array.from(byVoice.entries())
      .sort((a, b) => VOICE_ORDER.indexOf(a[0]) - VOICE_ORDER.indexOf(b[0]))
      .map(([voice, hits]) => ({ voice, hits: new Set(hits) }));
    return { rows, steps: totalSteps, tooShort };
  }, [section, song, model, transitionBars]);

  if (tooShort) {
    return <p className="text-3xs text-inkMuted italic">Section too short — a transition needs a full bar to give up.</p>;
  }
  if (rows.length === 0) {
    return <p className="text-3xs text-inkMuted italic">No hits generated for this transition.</p>;
  }

  const color = TRANSITION_COLOR[model];
  return (
    <div className="space-y-0.5">
      <div className="flex items-center justify-between">
        <span className="font-mono text-3xs uppercase tracking-wider" style={{ color }}>
          {TRANSITION_LABEL[model]} · these bars
        </span>
        <span className="font-mono text-3xs text-inkMuted/70">{steps} steps · what the export plays</span>
      </div>
      {rows.map(({ voice, hits }) => (
        <div key={voice} className="flex items-center gap-1.5">
          <span
            className="font-mono text-2xs w-10 shrink-0 text-right tabular-nums"
            style={{ color: voiceColor(voice, P) }}
          >
            {VOICE_LABEL[voice] ?? voice}
          </span>
          <div className="flex gap-px">
            {Array.from({ length: steps }).map((_, i) => (
              <div
                key={i}
                className="h-2.5 w-2.5 rounded-[2px]"
                style={{ background: hits.has(i) ? voiceColor(voice, P) : withAlpha(P.grid, 0.22) }}
              />
            ))}
          </div>
        </div>
      ))}
    </div>
  );
}
