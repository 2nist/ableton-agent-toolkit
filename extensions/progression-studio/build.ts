import * as esbuild from "esbuild";
import * as fs from "node:fs";
import * as path from "node:path";
import { fileURLToPath } from "node:url";
import { gzipSync } from "node:zlib";
import { PRESET_PROGRESSIONS } from "@music-theory/core";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const production = process.argv.includes("--production");
const manifest = JSON.parse(fs.readFileSync("manifest.json", "utf8"));

// The corpus model + tension table + melody model + song index live in
// @platform/progression-engine's data/ folder (produced by `npm run build:model`,
// `npm run build:melody` and `npm run build:songs` in that package).
const engineData = path.resolve(__dirname, "../../packages/progression-engine/data");
const modelJson = fs.readFileSync(path.join(engineData, "transition_model.json"), "utf8");
const tensionJson = fs.readFileSync(path.join(engineData, "tension.json"), "utf8");
const melodyJson = fs.readFileSync(path.join(engineData, "melody_model.json"), "utf8");
const presetsJson = JSON.stringify(PRESET_PROGRESSIONS);

// The song index is large (~390KB raw); gzip it to base64 so the modal's
// data: URL stays small. The webview decompresses it client-side (DecompressionStream).
const songsRaw = fs.readFileSync(path.join(engineData, "song_sections.json"));
const songsB64 = gzipSync(songsRaw).toString("base64");

// 1) Bundle the webview app (typed TS importing the engine) to one IIFE string.
const appResult = await esbuild.build({
  entryPoints: ["src/webview/app.ts"],
  bundle: true,
  format: "iife",
  platform: "browser",
  target: "es2020",
  minify: production,
  write: false,
});
const appJs = appResult.outputFiles[0].text;

// 2) Regenerate the bundle module the extension imports (kept on disk so
//    `tsc --noEmit` resolves it without a build first).
const gen =
  "// AUTO-GENERATED by build.ts — do not edit.\n" +
  `export const STUDIO_APP_JS = ${JSON.stringify(appJs)};\n` +
  `export const STUDIO_MODEL = ${JSON.stringify(modelJson)};\n` +
  `export const STUDIO_TENSION = ${JSON.stringify(tensionJson)};\n` +
  `export const STUDIO_MELODY = ${JSON.stringify(melodyJson)};\n` +
  `export const STUDIO_SONGS = ${JSON.stringify(songsB64)};\n` +
  `export const STUDIO_PRESETS = ${JSON.stringify(presetsJson)};\n`;
fs.writeFileSync(path.join(__dirname, "src/generated/studio-bundle.ts"), gen);

// 3) Bundle the extension itself.
await esbuild.build({
  entryPoints: ["src/extension.ts"],
  outfile: manifest.entry,
  bundle: true,
  format: "cjs",
  platform: "node",
  sourcesContent: false,
  logLevel: "info",
  minify: production,
  sourcemap: !production,
});

console.log(
  `[progression-studio] webview=${(appJs.length / 1024).toFixed(1)}KB model=${(modelJson.length / 1024).toFixed(1)}KB melody=${(melodyJson.length / 1024).toFixed(1)}KB songs=${(songsB64.length / 1024).toFixed(1)}KB(gz) presets=${Object.keys(PRESET_PROGRESSIONS).length}`,
);
