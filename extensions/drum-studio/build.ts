import * as esbuild from "esbuild";
import * as fs from "node:fs";
import * as path from "node:path";
import { fileURLToPath } from "node:url";
import { PRESET_DATA, type DrumPattern } from "@drum/library";
import {
  PATTERN_LABELS,
  BAR_OPTIONS,
  OUTLINE_NUMERATOR_OPTIONS,
  OUTLINE_DENOMINATOR_OPTIONS,
  TRANSITION_LABELS,
  selectablePatterns,
} from "./src/render-drum-studio.js";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const production = process.argv.includes("--production");
const manifest = JSON.parse(fs.readFileSync("manifest.json", "utf8"));

// Which patterns actually have preset data right now, in PATTERN_LABELS
// order — the picker only ever offers patterns with something to render.
const patternOrder = selectablePatterns(PRESET_DATA);

// Trimmed preview data (notes/lengthBeats/beatsPerBar only — no corpus
// provenance) for every selectable pattern's variants, for the modal's
// preview grid.
const patterns: Record<string, unknown> = {};
for (const pattern of patternOrder) {
  const preset = PRESET_DATA[pattern as DrumPattern]!;
  patterns[pattern] = preset.variants.map((v) => ({
    lengthBeats: v.lengthBeats,
    beatsPerBar: v.beatsPerBar,
    notes: v.notes,
  }));
}
const patternsJson = JSON.stringify(patterns);

// 1) Bundle the webview app (typed TS importing @drum/library + @platform/ui-kit
//    source directly) to one IIFE string.
const appResult = await esbuild.build({
  entryPoints: ["src/webview/app.ts"],
  bundle: true,
  format: "iife",
  platform: "browser",
  target: "es2020",
  minify: production,
  write: false,
});
const appJs = appResult.outputFiles[0].text;

// 2) Regenerate the bundle module the extension imports (kept on disk so
//    `tsc --noEmit` resolves it without a build first).
const gen =
  "// AUTO-GENERATED by build.ts — do not edit.\n" +
  `export const STUDIO_APP_JS = ${JSON.stringify(appJs)};\n` +
  `export const STUDIO_PATTERNS_JSON = ${JSON.stringify(patternsJson)};\n` +
  `export const STUDIO_PATTERN_ORDER = ${JSON.stringify(patternOrder)};\n` +
  `export const STUDIO_PATTERN_LABELS = ${JSON.stringify(PATTERN_LABELS)};\n` +
  `export const STUDIO_BAR_OPTIONS = ${JSON.stringify(BAR_OPTIONS)};\n` +
  `export const STUDIO_OUTLINE_NUMERATORS = ${JSON.stringify(OUTLINE_NUMERATOR_OPTIONS)};\n` +
  `export const STUDIO_OUTLINE_DENOMINATORS = ${JSON.stringify(OUTLINE_DENOMINATOR_OPTIONS)};\n` +
  `export const STUDIO_TRANSITION_LABELS = ${JSON.stringify(TRANSITION_LABELS)};\n` +
  `export const STUDIO_TRANSITION_ORDER = ${JSON.stringify(Object.keys(TRANSITION_LABELS))};\n`;
fs.writeFileSync(path.join(__dirname, "src/generated/studio-bundle.ts"), gen);

// 3) Bundle the extension itself.
await esbuild.build({
  entryPoints: ["src/extension.ts"],
  outfile: manifest.entry,
  bundle: true,
  format: "cjs",
  platform: "node",
  sourcesContent: false,
  logLevel: "info",
  minify: production,
  sourcemap: !production,
});

console.log(
  `[drum-studio] webview=${(appJs.length / 1024).toFixed(1)}KB patterns=${patternOrder.length} preview=${(patternsJson.length / 1024).toFixed(1)}KB`,
);
